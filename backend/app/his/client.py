"""ค้นหา HN จาก HIS ด้วยเลขบัตรประชาชน — รองรับ IF-HIS-01

หมายเหตุ: การเชื่อมต่อ HIS จริง (โปรโตคอล, endpoint, การยืนยันตัวตนกับ HIS) ยังไม่ได้ระบุใน spec.md/plan.md
จึงทำเป็น stub ที่จำลองผลการค้นหาไว้ก่อน (แนวทางเดียวกับที่ทีมอนุมัติไว้ตอน T-04 สำหรับ auth/idp.py)
ข้อสำคัญตาม IF-HIS-01 คือ "ไม่เก็บเลขบัตรประชาชนในตารางการจอง" — ฟังก์ชันนี้จึงไม่เขียนเลขบัตรประชาชน
ลงฐานข้อมูลใด ๆ เลย เพียงคำนวณและคืนค่า HN กลับไปให้ผู้เรียกใช้เท่านั้น
"""
import hashlib


def lookup_hn_by_national_id(national_id: str) -> str:
    """คืนค่า HN ที่สอดคล้องกับเลขบัตรประชาชน (stub จำลอง HIS — ยังไม่เชื่อมต่อระบบจริง)"""
    digest = hashlib.sha256(national_id.encode("utf-8")).hexdigest()[:8].upper()
    return f"HN-{digest}"
